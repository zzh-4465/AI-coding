const assert = require('node:assert/strict');
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const fs = require('node:fs');

(async () => {
  const browser = await chromium.launch({ headless: true, ...(process.env.CHROME_PATH ? { executablePath: process.env.CHROME_PATH } : {}) });
  try {
    const page = await browser.newPage({ viewport: { width: 390, height: 844 } });
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    await page.goto(process.env.APP_URL || 'http://localhost:5173');
    const input = title => page.getByRole('spinbutton', { name: `${title}分配金额`, exact: true });
    const start = page.getByRole('button', { name: '开始饭饭有余', exact: true });
    await page.locator('.onboard-budget input').fill('1000');
    assert.equal(await page.locator('.allocation-mini-slider').count(), 0);
    const slider = page.getByRole('slider', { name: '饮食池和应急必备池之间的分隔线', exact: true });
    await slider.focus(); await slider.press('ArrowUp');
    assert.equal(await input('饮食池').inputValue(), '550.00');
    await slider.press('ArrowDown');
    assert.equal(await input('饮食池').inputValue(), '560.00');
    await input('饮食池').fill('400');
    assert.equal(await slider.getAttribute('aria-disabled'), 'false');
    const savingsBefore = Number(await input('储蓄池').inputValue());
    await slider.focus(); await slider.press('ArrowDown');
    assert.equal(await input('饮食池').inputValue(), '400');
    assert.equal(Number(await input('储蓄池').inputValue()), savingsBefore + 10);
    await slider.scrollIntoViewIfNeeded();
    const rect = await slider.boundingBox();
    await page.mouse.move(rect.x + rect.width / 2, rect.y + rect.height / 2);
    await page.mouse.down(); await page.mouse.move(rect.x + rect.width / 2, rect.y + rect.height / 2 + 12, { steps: 5 }); await page.mouse.up();
    assert.equal(await input('饮食池').inputValue(), '400');
    assert.notEqual(Number(await input('储蓄池').inputValue()), savingsBefore + 10);
    await input('储蓄池').fill('300');
    await input('应急必备池').fill('250');
    assert.equal(await slider.getAttribute('aria-disabled'), 'true');
    assert.equal(await input('小余仓').inputValue(), '50.00');
    await page.getByText('剩余金额', { exact: true }).waitFor();
    await input('应急必备池').fill('350');
    assert.equal(await input('饮食池').inputValue(), '400');
    assert.equal(await input('储蓄池').inputValue(), '300');
    await page.getByRole('alert').filter({ hasText: '超出总预算 50.00 元，应急必备池最多可填 300.00 元' }).waitFor();
    assert.equal(await start.isDisabled(), true);
    fs.mkdirSync('tmp/verification', { recursive: true });
    await page.locator('.allocation-editor').scrollIntoViewIfNeeded();
    await page.screenshot({ path: 'tmp/verification/allocation-conflict.png' });
    await input('应急必备池').fill('250');
    await input('小余仓').fill('40');
    await page.getByRole('alert').filter({ hasText: '还有 10.00 元未分配' }).waitFor();
    assert.equal(await start.isDisabled(), true);
    await input('小余仓').fill('50');
    assert.equal(await start.isEnabled(), true);
    await page.getByRole('button', { name: '小余仓已固定，点击恢复自动分配' }).click();
    assert.equal(await input('小余仓').inputValue(), '50.00');
    await page.locator('.onboard-budget input').fill('900');
    assert.equal(await input('饮食池').inputValue(), '400');
    assert.equal(await start.isDisabled(), true);
    await page.locator('.onboard-budget input').fill('1000.01');
    await input('饮食池').fill('');
    assert.equal(await start.isDisabled(), true);
    await input('饮食池').fill('400.01');
    assert.equal(await input('小余仓').inputValue(), '50.00');
    await page.screenshot({ path: 'tmp/verification/allocation-fixed.png' });
    await start.click();
    const read = () => page.evaluate(() => JSON.parse(localStorage.getItem('fanfan-youyu-app-v5-android-clean')));
    const data = await read();
    assert.deepEqual(data.pools, { savings: 300, food: 400.01, emergency: 250, happy: 50 });
    await page.reload();
    assert.deepEqual((await read()).pools, data.pools);
    await page.getByRole('button', { name: '设置', exact: true }).click();
    await page.getByRole('button', { name: /下月预算/ }).click();
    await page.locator('.budget-sheet .onboard-budget input').fill('1000');
    await input('饮食池').fill('400');
    await input('储蓄池').fill('300');
    await input('应急必备池').fill('350');
    const save = page.getByRole('button', { name: '保存预算方案', exact: true });
    assert.equal(await save.isDisabled(), true);
    await input('应急必备池').fill('250');
    await save.click();
    const next = await read();
    assert.deepEqual(next.pools, data.pools);
    assert.equal(next.nextMonthBudget, 1000);
    assert.equal(next.nextRatios.food, 40);
    assert.equal(next.nextRatios.happy, 5);
    assert.deepEqual(errors, []);
    console.log('PASS: fixed amounts, auto remainder, conflicts, unlock, budget changes, cent persistence, next-month plan');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
