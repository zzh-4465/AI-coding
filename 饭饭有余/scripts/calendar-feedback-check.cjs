const assert = require('node:assert/strict');
const fs = require('node:fs');
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const key = 'fanfan-youyu-app-v5-android-clean';
(async () => {
  const browser = await chromium.launch({ headless: true, ...(process.env.CHROME_PATH ? { executablePath: process.env.CHROME_PATH } : {}) });
  try {
    const page = await browser.newPage({ viewport: { width: 390, height: 844 } });
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    await page.clock.install({ time: new Date('2026-08-30T23:59:40+08:00') });
    await page.goto(process.env.APP_URL || 'http://127.0.0.1:5173/', { waitUntil: 'domcontentloaded' });
    await page.locator('.onboarding-form').waitFor();
    assert.equal(await page.getByRole('button', { name: '开始饭饭有余' }).isDisabled(), true);
    await page.locator('.onboard-budget input').fill('1000');
    assert.equal(await page.getByRole('button', { name: '独立滑条' }).count(), 0);
    await page.locator('.allocation-stack').scrollIntoViewIfNeeded();
    const board = await page.locator('.allocation-stack').boundingBox();
    const beforePartition = (await page.locator('.allocation-layer b').allTextContents()).map(value => Number(value.replace('%', '')));
    const handle = await page.getByRole('slider', { name: '饮食池和应急必备池之间的分隔线' }).boundingBox();
    await page.mouse.move(handle.x + handle.width / 2, handle.y + handle.height / 2);
    await page.mouse.down();
    await page.mouse.move(board.x + board.width / 2, board.y + board.height * .62);
    await page.mouse.up();
    const partitionValues = (await page.locator('.allocation-layer b').allTextContents()).map(value => Number(value.replace('%', '')));
    assert.equal(partitionValues.reduce((sum, value) => sum + value, 0), 100);
    assert.equal(partitionValues[0], beforePartition[0]);
    assert.equal(partitionValues[3], beforePartition[3]);
    assert.notEqual(partitionValues[1], beforePartition[1]);
    assert.notEqual(partitionValues[2], beforePartition[2]);
    fs.mkdirSync('docs/verification', { recursive: true });
    await page.screenshot({ path: 'docs/verification/budget-partition.png', fullPage: true, animations: 'disabled' });
    await page.getByRole('button', { name: '开始饭饭有余' }).click();
    await page.locator('.today-hero').waitFor();
    await page.locator('.meal-item').first().click();
    await page.waitForTimeout(200);
    if (await page.locator('.transaction-sheet').count() !== 1) {
      throw new Error(`记账面板没有打开：${errors.join('; ') || '页面无报错'}`);
    }
    await page.locator('.transaction-sheet .pool-tabs button:nth-child(2)').click();
    await page.locator('.transaction-sheet .amount-field input').fill('1');
    await page.getByRole('button', { name: '确认记账', exact: true }).click();
    assert.equal(await page.locator('.transaction-sheet').count(), 1);
    await page.locator('.transaction-sheet .pool-tabs button:nth-child(1)').click();
    await page.locator('.transaction-sheet .amount-field input').fill('20');
    await page.getByRole('button', { name: '确认记账', exact: true }).click();
    const read = () => page.evaluate(key => JSON.parse(localStorage.getItem(key)), key);
    assert.equal((await read()).transactions.some(item => item.pool === 'food' && item.amount === -20 && item.title === ''), true);
    const allocatedFood = partitionValues[1] / 100 * 1000;
    assert.equal((await read()).dailyFoodBudgets['2026-08-30'], allocatedFood / 2);
    await page.clock.fastForward(70000);
    await page.waitForFunction(key => JSON.parse(localStorage.getItem(key)).dailyFoodBudgets['2026-08-31'] !== undefined, key);
    assert.equal((await read()).dailyFoodBudgets['2026-08-31'], allocatedFood - 20);
    await page.clock.fastForward(24 * 60 * 60 * 1000);
    await page.waitForFunction(key => JSON.parse(localStorage.getItem(key)).lastBudgetMonth === '2026-09', key);
    const month = await read();
    assert.equal(month.transactions.filter(item => item.batch === 'monthly-2026-09').reduce((sum, item) => sum + item.amount, 0), 1000);
    await page.reload({ waitUntil: 'domcontentloaded' });
    await page.locator('.today-hero').waitFor();
    assert.equal((await read()).transactions.length, month.transactions.length);
    console.log('PASS: stacked adjacent-only allocation, real midnight and month-boundary detection');

    await page.getByRole('button', { name: '账本', exact: true }).click();
    await page.getByLabel('选择年月').fill('2024-02');
    await page.getByRole('button', { name: '2024年2月29日', exact: true }).click();
    await page.locator('.selected-date-records .text-button').click();
    assert.equal(await page.getByLabel('记账日期').inputValue(), '2024-02-29');
    await page.locator('.transaction-sheet .amount-field input').fill('10');
    await page.locator('.transaction-sheet .text-field input').fill('闰年补记');
    await page.getByRole('button', { name: '确认记账', exact: true }).click();
    assert.equal((await read()).transactions.find(item => item.title === '闰年补记').date, '2024-02-29');
    await page.getByLabel('选择年月').fill('2026-12');
    await page.getByRole('button', { name: '2026年12月31日', exact: true }).click();
    await page.getByRole('button', { name: '下个月', exact: true }).click();
    assert.equal(await page.getByLabel('选择年月').inputValue(), '2027-01');
    await page.getByLabel('选择年月').fill('2024-02');
    await page.evaluate(() => window.scrollTo(0, 0));
    await page.screenshot({ path: 'docs/verification/calendar-navigation.png', fullPage: true, animations: 'disabled' });
    console.log('PASS: arbitrary year/month/day, leap date and historical entry date');

    await page.getByRole('button', { name: '设置', exact: true }).click();
    await page.getByRole('button', { name: /时间演练/ }).click();
    await page.locator('.simulation-banner').waitFor();
    const real = await page.evaluate(key => localStorage.getItem(key), key);
    await page.getByRole('button', { name: '下月 1 日', exact: true }).click();
    await page.locator('.simulation-banner').waitFor();
    assert.equal(await page.evaluate(key => localStorage.getItem(key), key), real);
    await page.getByRole('button', { name: '返回真实账本', exact: true }).click();
    await page.locator('.today-hero').waitFor();
    assert.equal(await page.evaluate(key => localStorage.getItem(key), key), real);
    await page.evaluate(key => {
      const current = JSON.parse(localStorage.getItem(key));
      current.pools.food = 0;
      localStorage.setItem(key, JSON.stringify(current));
    }, key);
    await page.reload({ waitUntil: 'domcontentloaded' });
    await page.locator('.month-callout').waitFor();
    assert.equal(await page.locator('.month-callout strong').textContent(), '饮食余粮已经见底');
    assert.equal((await page.locator('.month-callout').textContent()).includes('有余'), false);
    assert.deepEqual(errors, []);
    console.log('PASS: required notes, zero-balance outlook and isolated simulation; no page errors');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
